"""Optional codegen diagnostics; scheduling and capacity never parse wrappers."""

import ast

import pytest

from pllm.execution.codec import boundary_digest


def _kernel_calls(source_code):
    """Count generated calls in the pinned wrapper, excluding template trials.

    Inductor's global generation metric also counts discarded template code.
    Read the final artifact's call entry; never execute or evaluate its source.
    """
    module = ast.parse(source_code)
    entries = [node for node in module.body if isinstance(node, ast.FunctionDef) and node.name == "call"]
    if len(entries) != 1:
        raise AssertionError("compiled artifact has no single supported call entry")
    kernels: set[str] = set()
    for node in module.body:
        if (isinstance(node, ast.Assign) and isinstance(node.value, ast.Call)
            and isinstance(node.value.func, ast.Attribute) and isinstance(node.value.func.value, ast.Name)
            and node.value.func.value.id == "async_compile" and node.value.func.attr in ("triton", "cpp_pybinding")):
            kernels.update(target.id for target in node.targets if isinstance(target, ast.Name))
    count = 0
    for node in ast.walk(entries[0]):
        if isinstance(node, ast.Call):
            function = node.func
            if (isinstance(function, ast.Name) and function.id in kernels
                or isinstance(function, ast.Attribute) and function.attr == "run"
                and isinstance(function.value, ast.Name) and function.value.id in kernels):
                count += 1
    return count


@pytest.fixture
def compiled_kernel_calls(monkeypatch):
    # Inspect only code generated by this test, indexed by its existing identity.
    # This does not wrap the executable or introduce a production compiler ABI.
    import torch._inductor.compile_fx as inductor

    compile_fx_inner = inductor.compile_fx_inner
    artifacts = {}

    def record(*args, **kwargs):
        artifact = compile_fx_inner(*args, **kwargs)
        artifacts[boundary_digest(artifact.source_code)] = artifact.source_code
        return artifact

    monkeypatch.setattr(inductor, "compile_fx_inner", record)

    def count(implementation):
        return _kernel_calls(artifacts[implementation.code_digest])

    return count
