#!/usr/bin/env python3
"""ESamp consumer backed by the Program compiler (implementation="program").

The wrapper owns config validation, lazy specialization, and the sampler
bridge surface; everything else — bundle slicing, per-prompt state banking,
functional optimizer transitions, sink publication — is generated by
``tllm.program.compile_program`` from ``ESampProgram``'s declarations. This
module must never import ``ESampTrainEngine``: the legacy engine remains
available strictly as an explicit baseline (implementation="legacy").
"""

from __future__ import annotations

from typing import Sequence

import torch

from tllm.contracts.consumer_stats import TrainingStats
from tllm.contracts.gpu_stage import DeviceTensorLease
from tllm.contracts.port_bundle import PortBundle
from tllm.contracts.request_meta_view import RowBatchMeta
from tllm.contracts.runtime_context import RuntimeContext
from tllm.consumers.esamp.config import BaseESampConsumer, ESampConsumerConfig
from tllm.consumers.esamp.lm_head import resolve_lm_head
from tllm.consumers.esamp.program import ESampProgram
from tllm.ports.base import (
    BufferOwnership,
    ConsumerFlow,
    FlowFusion,
    RowSelection,
    TimingContract,
    TimingDeadline,
    TimingMobility,
    VersionObservation,
)
from tllm.ports.request_meta import RequestMeta
from tllm.ports.residual_stream import ResidualStream
from tllm.program import ProgramConsumer, StateSpec, compile_program
from tllm.runtime.sampler_bridge.provider import SamplerModifierProvider
from tllm.runtime.sampler_bridge.types import (
    CandidateModifierState,
    SamplerStepView,
)
from tllm.runtime.specialization import RuntimeSpecializationSpec
from tllm.workgraph.frontend import DynamicDim, StateScope, request_prompt_idx
from tllm.workgraph.lowering import WorkGraphError

_SOURCE_READ = ResidualStream.read(
    layer=0,
    site="block_output",
    phase="decode",
    role="source",
)
_TARGET_READ = ResidualStream.read(
    layer=-1,
    site="block_output",
    phase="decode",
    role="target",
)

_STATE_NAME = "distiller"


def validate_program_config(config: ESampConsumerConfig) -> None:
    """Fail at startup on every combination the program path does not implement."""
    prefix = "ESamp implementation='program'"
    if config.per_request_model_bank:
        raise ValueError(
            f"{prefix} does not support per_request_model_bank=True "
            "(batched slot bank + SVD initializer); use implementation='legacy'"
        )
    if config.model_bank_train_cudagraph:
        raise ValueError(f"{prefix} does not support model_bank_train_cudagraph=True")
    if config.model_bank_initializer is not None:
        raise ValueError(f"{prefix} does not support model_bank_initializer")
    if config.trace_per_request_losses:
        raise ValueError(f"{prefix} does not support trace_per_request_losses=True")
    if bool(config.enable_distiller_intervention):
        if config.per_request_models:
            raise ValueError(
                f"{prefix} does not support distiller intervention with "
                "per_request_models=True (legacy never intervenes in that mode)"
            )
        if str(config.distiller_sampler_backend) != "post_filter_exact":
            raise ValueError(
                f"{prefix} supports only distiller_sampler_backend='post_filter_exact', "
                f"got {config.distiller_sampler_backend!r}"
            )


class _GuidanceSink:
    """Receives the flow's published prediction for the sampler provider."""

    def __init__(self) -> None:
        self.latest: tuple[int, torch.Tensor, tuple[int, ...]] | None = None

    @property
    def name(self) -> str:
        return "guidance"

    def publish(self, value: torch.Tensor, meta: RowBatchMeta | None) -> None:
        step_id = -1 if meta is None else int(meta.engine_step_id)
        rows = int(value.shape[0]) if value.ndim > 0 else 0
        prompt_idxs = (
            () if meta is None else tuple(int(p) for p in meta.prompt_idxs[:rows])
        )
        self.latest = (step_id, value.detach(), prompt_idxs)


class _ProgramSamplerModifierProvider(SamplerModifierProvider):
    """Same-step intervention: predict from the current source hidden.

    Mirrors the legacy provider's on-demand prediction (one-step-stale flow
    outputs would miss the current step's sampler): the predict flow runs
    read-only against the current bank state at sampler time.
    """

    def __init__(
        self, *, config: ESampConsumerConfig, consumer: "ESampProgramConsumer"
    ) -> None:
        self._config = config
        self._consumer = consumer
        self.published_state_count = 0

    def is_active(self) -> bool:
        return (
            bool(self._config.enable_distiller_intervention)
            and bool(self._config.enable_esamp_training)
            and float(self._config.distiller_beta or 0.0) != 0.0
        )

    def prepare_step(self, view: SamplerStepView) -> CandidateModifierState | None:
        if not self.is_active():
            return None
        compiled = self._consumer.compiled
        if compiled is None:
            return None
        rows = int(view.decode_count)
        if rows <= 0 or view.source_hidden.ndim != 2:
            return None
        if int(view.source_hidden.shape[0]) < rows:
            return None
        source = view.source_hidden[:rows]
        prediction = compiled.run_flow("predict", source)["prediction"]
        if prediction.ndim != 2 or int(prediction.shape[0]) != rows:
            raise WorkGraphError(
                "PG190",
                f"predict flow returned {tuple(prediction.shape)} for {rows} decode rows",
            )
        lm_head = resolve_lm_head(view.model)
        try:
            lm_head_bias = lm_head.bias
        except AttributeError:
            lm_head_bias = None
        self.published_state_count += 1
        return CandidateModifierState(
            beta=float(self._config.distiller_beta),
            backend=self._config.distiller_sampler_backend,
            affected_row_ids=torch.arange(rows, device=prediction.device, dtype=torch.long),
            pred_hidden=prediction,
            lm_head_weight=lm_head.weight,
            lm_head_bias=lm_head_bias,
        )


class ESampProgramConsumer(BaseESampConsumer):
    """Dispatch-plan friendly ESamp consumer generated by the Program compiler."""

    def __init__(self, config: ESampConsumerConfig) -> None:
        validate_program_config(config)
        self.config = config
        self._sink = _GuidanceSink()
        self._provider = _ProgramSamplerModifierProvider(config=config, consumer=self)
        self._compiled: ProgramConsumer | None = None
        self._disabled_skip_count = 0

    @property
    def consumer_id(self) -> str:
        return self.config.consumer_id

    @property
    def compiled(self) -> ProgramConsumer | None:
        """The compiled program, present after cold specialization."""
        return self._compiled

    def flows(self) -> Sequence[ConsumerFlow]:
        if not bool(self.config.enable_esamp_training):
            return ()
        return [
            ConsumerFlow(
                reads=(
                    _SOURCE_READ,
                    _TARGET_READ,
                    RequestMeta.read(),
                ),
                writes=(),
                window="out_of_band",
                delivery="device_lease",
                ownership=BufferOwnership.RUNTIME_LEASE,
                lease_lifetime="step",
                row_compaction=(
                    RowSelection.FIRST_PER_PROMPT
                    if self.config.training_row_selection == RowSelection.FIRST_PER_PROMPT
                    else RowSelection.ALL
                ),
                max_bundle_rows=max(0, int(self.config.graph_scratch_rows)),
                fusion=FlowFusion.NONE,
                bundle_key=("engine_step_id", "phase"),
                timing=TimingContract(
                    mobility=TimingMobility.DEFERRABLE,
                    deadline=TimingDeadline.NEXT_PREPARE,
                    max_defer_steps=1,
                    observes_version=VersionObservation.AT_DECLARED_WINDOW,
                ),
            )
        ]

    def _compile(self, source: torch.Tensor, target: torch.Tensor) -> ProgramConsumer:
        if source.ndim != 2 or source.shape != target.shape:
            raise ValueError(
                "ESamp program specialization requires matching rank-2 "
                f"source/target rows, got {tuple(source.shape)} / {tuple(target.shape)}"
            )
        if int(source.shape[0]) < 2:
            # Strict export requires example rows strictly above the dynamic
            # lower bound; pad the specialization example (values are inert —
            # the oracle trains on a deep copy, never on the live instance).
            source = source.repeat(2, 1)
            target = target.repeat(2, 1)
        hidden_size = int(source.shape[1])
        rank = max(1, min(int(self.config.distiller_hidden_dim), hidden_size))
        program = ESampProgram(
            hidden_size=hidden_size,
            rank=rank,
            lr=float(self.config.distiller_lr),
            device=source.device,
            dtype=source.dtype,
        )
        scope = (
            StateScope.REQUEST
            if bool(self.config.per_request_models)
            else StateScope.REPLICA
        )
        compiled = compile_program(
            program,
            states={
                _STATE_NAME: StateSpec(
                    scope=scope,
                    key=(
                        request_prompt_idx() if scope is StateScope.REQUEST else None
                    ),
                    optimizer=torch.optim.AdamW,
                )
            },
            examples={"forward": (source, target), "predict": (source,)},
            sinks=(self._sink,),
            dynamic_dims={
                "forward": (
                    DynamicDim(value_path=(0,), dimension=0, lower_bound=1, upper_bound=65536),
                    DynamicDim(value_path=(1,), dimension=0, lower_bound=1, upper_bound=65536),
                ),
                "predict": (
                    DynamicDim(value_path=(0,), dimension=0, lower_bound=1, upper_bound=65536),
                ),
            },
        )
        self._compiled = compiled
        return compiled

    def _ensure_compiled(self, bundle: PortBundle) -> ProgramConsumer:
        compiled = self._compiled
        if compiled is not None:
            return compiled
        lease = bundle.entries.get("device_lease")
        if not isinstance(lease, DeviceTensorLease):
            raise WorkGraphError(
                "PG100", "ESamp program specialization requires a device_lease bundle"
            )
        rows = int(lease.active_rows)
        try:
            source = lease.entries["source"][:rows]
            target = lease.entries["target"][:rows]
        except KeyError as exc:
            raise WorkGraphError(
                "PG100", f"ESamp program input {exc} missing from device_lease"
            ) from exc
        return self._compile(source, target)

    def cold_specialize_workgraph(self, spec: RuntimeSpecializationSpec) -> None:
        if not bool(self.config.enable_esamp_training) or self._compiled is not None:
            return
        source = torch.empty(
            (max(1, int(spec.rows)), int(spec.hidden_size)),
            dtype=spec.dtype,
            device=spec.device,
        )
        self._compile(source, torch.empty_like(source))

    def consume_flow(
        self, flow_ordinal: int, bundle: PortBundle, ctx: RuntimeContext
    ) -> None:
        if not bool(self.config.enable_esamp_training):
            self._disabled_skip_count += 1
            return
        self._ensure_compiled(bundle).consume_flow(flow_ordinal, bundle, ctx)

    def consume_bundle(self, bundle: PortBundle, ctx: RuntimeContext) -> None:
        self.consume_flow(0, bundle, ctx)

    def update_config(self, config: ESampConsumerConfig) -> None:
        validate_program_config(config)
        self.config = config
        self._provider._config = config
        self._compiled = None
        self._sink.latest = None

    def set_enabled(self, enabled: bool) -> None:
        self.config.enable_esamp_training = bool(enabled)

    def synchronize(self) -> None:
        """Program execution is inline on the current stream; nothing pending."""

    def sampler_modifier_provider(self) -> _ProgramSamplerModifierProvider:
        return self._provider

    def read_and_reset_stats(self, sync: bool = True) -> TrainingStats:
        del sync
        compiled = self._compiled
        if compiled is None or compiled.loss_count <= 0:
            return TrainingStats(loss_avg=0.0, loss_count=0)
        stats = TrainingStats(
            loss_avg=compiled.loss_sum / max(1, compiled.loss_count),
            loss_count=compiled.loss_count,
        )
        compiled._loss_sum = None
        compiled.loss_count = 0
        return stats

    def read_and_reset_per_request_stats(self, sync: bool = True) -> dict[int, TrainingStats]:
        del sync
        compiled = self._compiled
        if compiled is None:
            return {}
        out: dict[int, TrainingStats] = {}
        for (bank, slot_id), (loss_sum, loss_count) in compiled.read_and_reset_slot_losses().items():
            if bank != _STATE_NAME:
                continue
            out[int(slot_id)] = TrainingStats(
                loss_avg=loss_sum / max(1, loss_count),
                loss_count=loss_count,
            )
        return out


__all__ = ["ESampProgramConsumer", "validate_program_config"]
